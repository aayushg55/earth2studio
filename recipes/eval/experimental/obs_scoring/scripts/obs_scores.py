"""Score 0.25 deg lat-lon stores against conventional observations (command line).

The work is done by ``private.obs_scoring``; usage and outputs: private/obs_scoring/README.md.

    python -m private.scripts.analysis.obs_scores fetch --start 2025-07-08 --end 2025-08-05T18 --cache DIR
    python -m private.scripts.analysis.obs_scores fetch --config RUN/resolved_config.yaml [--check]
    python -m private.scripts.analysis.obs_scores score --start 2025-07-08 --end 2025-08-05T18 \\
        --cache DIR --out OUT --system healda=zarr:STORE.zarr --system era5=era5
    python -m private.scripts.analysis.obs_scores compare --out OUT
"""

from __future__ import annotations

import argparse
import functools
import multiprocessing
import os
import pathlib
import re
import sys

import pandas as pd
import pyarrow as pa
import pyarrow.parquet as pq
import xarray as xr
import yaml

from healda.config.environment import nnja_archive
from private.obs_scoring import fields, observations, report
from private.obs_scoring.score import cycle_observations, score_cycle
from private.obs_scoring.score import field_units
from private.scripts import region_masks


# Lead step of every campaign model (build_campaign.py run.step_hours); a resolved config
# records only nsteps.
CAMPAIGN_STEP = pd.Timedelta(hours=6)


def campaign_observations(path: pathlib.Path):
    """The mirror a campaign config (generated by build_campaign.py, or a run's
    resolved_config.yaml) scores from and the valid times it scores; None without an
    ``observations`` block."""
    config = yaml.safe_load(path.read_text())
    settings = ((config.get("scoring") or {}).get("online") or {}).get("observations")
    if not settings:
        return None
    cache = re.sub(
        r"\$\{oc\.env:(\w+)\}", lambda m: os.environ[m[1]], str(settings["cache"])
    )
    leads = [CAMPAIGN_STEP * k for k in range(config["nsteps"] + 1)]
    starts = pd.to_datetime(config["start_times"])
    cycles = sorted({start + lead for start in starts for lead in leads})
    return pathlib.Path(cache), cycles


def run_fetch(args, parser):
    if args.config:
        scored = campaign_observations(args.config)
        if scored is None:
            print(f"{args.config} scores no observations")
            return
        cache, cycles = scored
        again = f"--config {args.config}"
    else:
        if None in (args.start, args.end, args.cache):
            parser.error("fetch needs --config, or --start, --end and --cache")
        cache = args.cache
        cycles = pd.date_range(args.start, args.end, freq="6h")
        again = f"--cache {cache} --start {args.start} --end {args.end}"
    days = observations.needed_days(cycles)
    missing = observations.missing_days(cache, cycles)
    if not args.check:
        observations.fetch(cache, missing, args.workers)
    elif missing:
        print(
            f"observation mirror {cache} lacks {len(missing)} of {len(days)} days "
            f"({missing[0]:%Y-%m-%d} .. {missing[-1]:%Y-%m-%d}); on a node with network:\n"
            f"  python3 -m private.scripts.analysis.obs_scores fetch {again}",
            file=sys.stderr,
        )
        sys.exit(1)
    else:
        print(f"observation mirror {cache} holds all {len(days)} days")


@functools.cache
def standard_regions() -> dict:
    return region_masks.load_regions()


@functools.cache
def _fields(spec: str):
    return fields.open_fields(spec)


_worker_regions = {}


def _init_worker(regions: dict):
    _worker_regions.update(regions)


def _score_cycle(task):
    system, spec, source, cycle, stations, pairs, vertical, by, options = task
    obs = cycle_observations(source, cycle, stations, options["dedupe_surface"])
    if obs is None:
        return system, None, None
    table, paired = score_cycle(
        lambda names: _fields(spec).at(cycle, names),
        obs,
        cycle,
        _worker_regions,
        by,
        vertical,
        options["elevation_correct"],
        pairs,
    )
    return system, table, paired


def run_score(args):
    cycles = pd.date_range(args.start, args.end, freq="6h")
    args.out.mkdir(parents=True, exist_ok=True)
    pairs = args.out / "pairs" / args.stations if args.pairs else None
    systems = dict(item.partition("=")[::2] for item in args.system)
    if args.obs == "conventional" and args.cache is None:
        raise SystemExit(
            "--obs conventional needs --cache (the NNJA-AI mirror from fetch)"
        )
    source = (args.obs, args.cache if args.obs == "conventional" else args.archive)
    options = {
        "dedupe_surface": args.dedupe_surface,
        "elevation_correct": args.elevation_correct,
    }
    tasks = [
        (
            system,
            spec,
            source,
            c,
            args.stations,
            args.pairs,
            args.vertical,
            _by(args),
            options,
        )
        for system, spec in systems.items()
        for c in cycles
    ]
    parts = {system: [] for system in systems}
    writers = {}
    # One pool for every system; workers get the region table instead of loading it.
    with multiprocessing.Pool(
        args.workers, initializer=_init_worker, initargs=(standard_regions(),)
    ) as pool:
        for system, table, paired in pool.imap(_score_cycle, tasks, chunksize=4):
            if table is not None and not table.empty:
                parts[system].append(table)
            if paired is not None and len(paired):
                batch = pa.Table.from_pandas(paired, preserve_index=False)
                if system not in writers:
                    pairs.mkdir(parents=True, exist_ok=True)
                    path = pairs / f"{system}.parquet"
                    writers[system] = pq.ParquetWriter(path, batch.schema)
                writer = writers[system]
                writer.write_table(
                    batch.select(writer.schema.names).cast(writer.schema)
                )
    for writer in writers.values():
        writer.close()
    for system in systems:
        if not parts[system]:
            print(f"{system}: no cycle scored, nothing written", flush=True)
            continue
        table = pd.concat(parts[system], ignore_index=True)
        table.insert(1, "system", system)
        table["stations"] = args.stations
        path = report.score_store(args.out, system, _label(args))
        report.to_dataset(table).to_zarr(path, mode="w")
        print(f"{system}: {table.time.nunique()} cycles -> {path}", flush=True)


def _by(args) -> tuple[str, ...]:
    return ("dataset", "field") if args.by_dataset else ("field",)


def _label(args) -> str:
    return f"{args.stations}_by_dataset" if args.by_dataset else args.stations


def run_compare(args):
    regions = standard_regions()
    mask = functools.partial(observations.station_mask, stations=args.stations)
    groups = list(_by(args))
    if args.gross is None:
        paths = report.system_score_stores(args.out, _label(args))
        if not paths:
            raise SystemExit(f"no */scores_{_label(args)}.zarr in {args.out}")
        table = pd.concat(
            [report.from_dataset(xr.open_zarr(p).load()) for p in paths],
            ignore_index=True,
        )
        label = _label(args)
    else:
        table = report.from_pairs(
            args.out / "pairs" / "all", args.gross, regions, mask, _by(args), args.match
        )
        table["stations"] = args.stations
        label = f"{_label(args)}_gross{args.gross:g}"
    label = f"{label}_{args.match}"
    if "match" in table:
        table = table[table["match"] == args.match]
    table = report.common_cycles(table)
    summary = report.pooled(table, ["stations", "region", *groups, "system"])
    summary["units"] = summary["field"].map(field_units)
    shown = summary[summary.field.isin(args.fields) & (summary.region == args.region)]
    for metric in ("rmse", "bias"):
        pivot = shown.pivot(index=groups, columns="system", values=metric)
        pivot["units"] = [
            field_units(key[-1] if args.by_dataset else key) for key in pivot.index
        ]
        pivot["count"] = shown.groupby(groups)["count"].first().astype(int)
        if not args.by_dataset:
            pivot = pivot.reindex(args.fields)
        print(f"\n{metric} ({args.region}, {label}, {table.time.nunique()} cycles)")
        print(pivot.to_markdown(floatfmt=".4g"))
    if not args.by_dataset:
        report.plot_profiles(summary[summary.region == args.region], args.out, label)


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = parser.add_subparsers(dest="command", required=True)
    fetch = sub.add_parser("fetch", help="mirror the NNJA-AI day files the cycles need")
    score_parser = sub.add_parser("score", help="score systems against observations")
    compare_parser = sub.add_parser("compare", help="pool scores and compare systems")
    for p in (fetch, score_parser):
        required = p is score_parser
        p.add_argument("--start", type=pd.Timestamp, required=required)
        p.add_argument("--end", type=pd.Timestamp, required=required)
        p.add_argument("--workers", type=int, default=16)
    fetch.add_argument("--cache", type=pathlib.Path)
    fetch.add_argument(
        "--config",
        type=pathlib.Path,
        help="a generated campaign config or a run's resolved_config.yaml: the days "
        "it scores, into its cache",
    )
    fetch.add_argument(
        "--check",
        action="store_true",
        help="no download: exit 1 and print the fetch command if a day is missing",
    )
    score_parser.add_argument(
        "--obs", choices=observations.OBS_SETS, default="conventional"
    )
    score_parser.add_argument(
        "--cache",
        type=pathlib.Path,
        help="NNJA-AI mirror from fetch (--obs conventional)",
    )
    score_parser.add_argument(
        "--archive",
        default=nnja_archive("parquet", "cycles"),
        help="NNJA PrepBUFR parquet archive (--obs vad/aircraft)",
    )
    score_parser.add_argument("--out", type=pathlib.Path, required=True)
    score_parser.add_argument(
        "--system",
        action="append",
        required=True,
        help="NAME=era5, NAME=zarr:PATH or NAME=wb2:PATH",
    )
    score_parser.add_argument("--pairs", action="store_true")
    score_parser.add_argument(
        "--elevation-correct",
        action="store_true",
        help="move model tas (lapse rate) and sp (hydrostatic) to the station elevation; "
        "not done by eagle-tools",
    )
    score_parser.add_argument(
        "--dedupe-surface",
        action="store_true",
        help="one surface report per field, time and position, SYNOP before METAR; "
        "not done by eagle-tools",
    )
    score_parser.add_argument(
        "--vertical",
        choices=["pressure", "height"],
        default="pressure",
        help="profile obs: log-p at the reported pressure, or linear in height at the "
        "reported height using model geopotential",
    )
    for p in (score_parser, compare_parser):
        p.add_argument("--stations", choices=["all", "withheld", "kept"], default="all")
        p.add_argument(
            "--by-dataset",
            action="store_true",
            help="separate scores per observation dataset",
        )
    compare_parser.add_argument("--out", type=pathlib.Path, required=True)
    compare_parser.add_argument("--region", default="global")
    compare_parser.add_argument(
        "--gross",
        type=float,
        help="score from pairs/all on common points, with a consensus gross-error "
        "check in scaled MADs (0: no check)",
    )
    compare_parser.add_argument(
        "--match",
        choices=observations.MATCHES,
        default="synoptic",
        help="radiosonde time match: strict [t-30, t+30) min as eagle-tools, or "
        "synoptic [t-90, t+30) min (private/obs_scoring/README.md)",
    )
    compare_parser.add_argument(
        "--fields", nargs="+", default=["Z500", "T850", "U500", "Q700", "tas", "sp"]
    )
    args = parser.parse_args()
    if args.command == "fetch":
        run_fetch(args, parser)
    elif args.command == "score":
        run_score(args)
    else:
        run_compare(args)


if __name__ == "__main__":
    main()
